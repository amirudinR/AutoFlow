export function getLanguageCode(language: string): string {
  return languageNameToCode[language] ?? 'en';
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) =>
    params[key] !== undefined ? String(params[key]) : `{${key}}`
  );
}

const I18nContext = createContext<string>('en');

export function I18nProvider({ language, children }: { language: string; children: ReactNode }) {
  const code = getLanguageCode(language);
  useEffect(() => {
    document.documentElement.dir = rtlLangs.has(code) ? 'rtl' : 'ltr';
  }, [code]);
  return <I18nContext.Provider value={code}>{children}</I18nContext.Provider>;
}

export type TranslateFn = (key: string, params?: Record<string, string | number>) => string;

export function useT(): TranslateFn {
  const code = useContext(I18nContext);
  return (key: string, params?: Record<string, string | number>) => {
    const table = translations[code] ?? translations.en;
    const template = table[key] ?? translations.en[key] ?? key;
    return interpolate(template, params);
  };
}